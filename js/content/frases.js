// Orden revuelto pero fijo para cada año: no se repite una frase hasta pasar por todas.
function seeded(seed) { let x = seed >>> 0 || 1; return () => { x ^= x << 13; x >>>= 0; x ^= x >> 17; x ^= x << 5; x >>>= 0; return x / 4294967296; }; }
const orders = new Map();
function orderOf(year, n) {
  const key = `${year}:${n}`;
  if (!orders.has(key)) { const r = seeded(year * 7919 + n), o = Array.from({ length: n }, (_, i) => i); for (let i = n - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [o[i], o[j]] = [o[j], o[i]]; } orders.set(key, o); }
  return orders.get(key);
}
const dayOfYear = (s) => { const [y, m, d] = s.split('-').map(Number); return Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 864e5); };
// La frase de un día (AAAA-MM-DD). Con partido ese día, una de partido.
export function fraseDelDia(day, { partido = false, extra = [] } = {}) {
  const list = [...FRASES, ...extra];
  const y = Number(day.slice(0, 4)), i = dayOfYear(day);
  if (partido) { const ps = list.filter((f) => f.k === 'p'); return ps[orderOf(y + 1, ps.length)[i % ps.length]]; }
  return list[orderOf(y, list.length)[i % list.length]];
}
